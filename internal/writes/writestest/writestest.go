// Package writestest is a test harness for the write path (ADR 0117): booth-api's own store on the
// test PostgreSQL, a workspace table in the same schema, and fakes for the parts that need real
// booth-core and booth-database (minting, the broker, the write sidecar).
//
// The fakes keep the database half honest: a NOLOGIN role stands in for booth-database's per-grant
// write group, the fake broker grants it exactly what a full-scope `tablewrite` request names
// (SELECT, DELETE if declared, column-level INSERT/UPDATE, sequence USAGE) and revokes everything
// on a revoke request, and every write-pool connection runs SET ROLE to it. So a write the settings
// don't cover really fails with SQLSTATE 42501, and the reissue really fixes it.
package writestest

