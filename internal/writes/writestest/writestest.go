// Table is the fixture workspace table writes go to.
const Table = `CREATE TABLE entries (
	id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	amount     numeric(12,2) NOT NULL,
	note       text,
	entered_by text NOT NULL,
	booked     date NOT NULL DEFAULT current_date,
	secret     text,
	CONSTRAINT amount_positive CHECK (amount > 0)
);
CREATE UNIQUE INDEX entries_note_unique ON entries (note);
CREATE TABLE other (x int);`

// Env is one test's write stack.
type Env struct {
	T       *testing.T
	Pool    *pgxpool.Pool // superuser, test schema
	Store   *store.Store
	Schema  string
	Role    string // stands in for booth-database's write group
	Minter  *Minter
	Broker  *Broker
	Pools   *Pools
	Service writes.Service
}

// New builds the harness. The test is skipped without the test PostgreSQL (dbtest).
func New(t *testing.T) *Env {
	t.Helper()
	ctx := context.Background()
	pool := dbtest.Pool(t)
	if err := store.Migrate(ctx, pool); err != nil {
		t.Fatal(err)
	}
	e := &Env{T: t, Pool: pool, Store: store.New(pool)}
	if err := pool.QueryRow(ctx, `SELECT current_schema()`).Scan(&e.Schema); err != nil {
		t.Fatal(err)
	}
	e.Role = e.Schema + "_w"
	for _, q := range []string{Table, `CREATE ROLE ` + e.Role + ` NOLOGIN`} {
		if _, err := pool.Exec(ctx, q); err != nil {
			t.Fatal(err)
		}
	}
	t.Cleanup(func() {
		_, _ = pool.Exec(context.Background(), `DROP OWNED BY `+e.Role+`; DROP ROLE IF EXISTS `+e.Role)
	})
	e.Minter = &Minter{}
	e.Broker = &Broker{env: e}
	e.Pools = &Pools{env: e, pools: map[string]*pgxpool.Pool{}}
	t.Cleanup(e.Pools.closeAll)
	e.Service = writes.Service{
		Store: e.Store, Pools: e.Pools, Minter: e.Minter, Broker: e.Broker,
		Limiter: ratelimit.New(1000, 1000), Timeout: table.DefaultLimits.StatementTimeout, IdempotencyTTL: writes.DefaultIdempotencyTTL,
	}
	return e
}

// API stores an API over the fixture table (or another table in the test schema).
func (e *Env) API(name string) apidef.Definition {
	e.T.Helper()
	ctx := context.Background()
	ref := apidef.TableRef{Schema: e.Schema, Name: name}
	tbl, err := source.Introspect(ctx, e.Pool, ref)
	if err != nil {
		e.T.Fatal(err)
	}
	d, err := e.Store.CreateAPI(ctx, apidef.Definition{Workspace: "acme", DatasetID: "ds-" + name, DatasetName: name, Table: ref,
		Columns: tbl.Columns, PrimaryKey: tbl.PrimaryKey, CreatedBy: "ed"})
	if err != nil {
		e.T.Fatal(err)
	}
	return d
}

// Minter is a fake core minting endpoint. Refuse makes it refuse an owner.
type Minter struct {
	mu       sync.Mutex
	Requests []workload.Request
	Refuse   map[string]bool
}

func (m *Minter) Mint(_ context.Context, r workload.Request) (workload.Token, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	m.Requests = append(m.Requests, r)
	if m.Refuse[r.Owner] {
		return workload.Token{}, source.ErrOwnerNoAccess
	}
	return workload.Token{JWT: "jwt:" + r.Subject + ":" + r.Owner, Role: r.RoleCeiling}, nil
}

// BrokerCall is one recorded broker request.
type BrokerCall struct {
	Token, Workspace, OnBehalfOf string
	Scope                        json.RawMessage
	Revoke                       bool
	Grant                        string
}

// Broker is a fake broker plus booth-database provider, applying scopes to the stand-in role.
type Broker struct {
	env   *Env
	mu    sync.Mutex
	Calls []BrokerCall
	// Err, if set, is returned instead of applying anything.
	Err error
	// Ignore answers success without applying the scope (a provider that doesn't help).
	Ignore bool
}

type scopeDoc struct {
	Workspace string `json:"workspace"`
	Write     struct {
		Grant  string `json:"grant"`
		Tables []struct {
			Schema     string   `json:"schema"`
			Name       string   `json:"name"`
			Operations []string `json:"operations"`
			Columns    []string `json:"columns"`
		} `json:"tables"`
	} `json:"write"`
}

func (b *Broker) TableWrite(ctx context.Context, token, workspace string, scope json.RawMessage, onBehalfOf string) error {
	b.mu.Lock()
	defer b.mu.Unlock()
	var doc scopeDoc
	_ = json.Unmarshal(scope, &doc)
	b.Calls = append(b.Calls, BrokerCall{Token: token, Workspace: workspace, OnBehalfOf: onBehalfOf, Scope: scope, Grant: doc.Write.Grant})
	if b.Err != nil {
		return b.Err
	}
	if b.Ignore {
		return nil
	}
	return b.env.Apply(ctx, scope)
}

func (b *Broker) RevokeTableWrite(ctx context.Context, token, workspace, grant, onBehalfOf string) error {
	b.mu.Lock()
	defer b.mu.Unlock()
	b.Calls = append(b.Calls, BrokerCall{Token: token, Workspace: workspace, OnBehalfOf: onBehalfOf, Revoke: true, Grant: grant})
	if b.Err != nil {
		return b.Err
	}
	return b.env.RevokeAll(ctx)
}

// Last returns the most recent broker call.
func (b *Broker) Last() BrokerCall {
	b.mu.Lock()
	defer b.mu.Unlock()
	if len(b.Calls) == 0 {
		return BrokerCall{}
	}
	return b.Calls[len(b.Calls)-1]
}

// Count returns how many broker calls were made.
func (b *Broker) Count() int {
	b.mu.Lock()
	defer b.mu.Unlock()
	return len(b.Calls)
}

// Apply grants the stand-in role exactly what scope names, as booth-database's issuance does.
func (e *Env) Apply(ctx context.Context, scope json.RawMessage) error {
	var doc scopeDoc
	if err := json.Unmarshal(scope, &doc); err != nil {
		return err
	}
	if err := e.RevokeAll(ctx); err != nil {
		return err
	}
	for _, t := range doc.Write.Tables {
		tbl := pgx.Identifier{t.Schema, t.Name}.Sanitize()
		cols := make([]string, len(t.Columns))
		for i, c := range t.Columns {
			cols[i] = pgx.Identifier{c}.Sanitize()
		}
		stmts := []string{
			`GRANT USAGE ON SCHEMA ` + pgx.Identifier{t.Schema}.Sanitize() + ` TO ` + e.Role,
			`GRANT SELECT ON ` + tbl + ` TO ` + e.Role,
			`GRANT USAGE ON ALL SEQUENCES IN SCHEMA ` + pgx.Identifier{t.Schema}.Sanitize() + ` TO ` + e.Role,
		}
		for _, op := range t.Operations {
			switch op {
			case "insert":
				stmts = append(stmts, `GRANT INSERT (`+strings.Join(cols, ", ")+`) ON `+tbl+` TO `+e.Role)
			case "update":
				stmts = append(stmts, `GRANT UPDATE (`+strings.Join(cols, ", ")+`) ON `+tbl+` TO `+e.Role)
			case "delete":
				stmts = append(stmts, `GRANT DELETE ON `+tbl+` TO `+e.Role)
			}
		}
		for _, s := range stmts {
			if _, err := e.Pool.Exec(ctx, s); err != nil {
				return fmt.Errorf("%s: %w", s, err)
			}
		}
	}
	return nil
}

// RevokeAll takes every privilege away from the stand-in role.
func (e *Env) RevokeAll(ctx context.Context) error {
	_, err := e.Pool.Exec(ctx, `DROP OWNED BY `+e.Role)
	return err
}

// Pools is a fake write-sidecar manager: a pool per (API, owner) whose connections SET ROLE to the
// stand-in write group. Starting one issues the full scope, as the real sidecar's first lease
// request does.
type Pools struct {
	env   *Env
	mu    sync.Mutex
	pools map[string]*pgxpool.Pool
	Specs []sidecars.WriteSpec
	Stops []string // "api/owner/why"
}

func (p *Pools) WritePool(ctx context.Context, w sidecars.WriteSpec) (*pgxpool.Pool, error) {
	p.mu.Lock()
	defer p.mu.Unlock()
	p.Specs = append(p.Specs, w)
	if p.env.Minter.Refuse[w.Owner] {
		return nil, source.ErrOwnerNoAccess
	}
	k := fmt.Sprintf("%s/%s/%d", w.APIID, w.Owner, w.Version)
	if pool, ok := p.pools[k]; ok {
		return pool, nil
	}
	// A new sidecar's first lease request issues the full scope, unless the fake provider ignores
	// scopes (Broker.Ignore).
	if !p.env.Broker.Ignore {
		if err := p.env.Apply(ctx, w.Scope); err != nil {
			return nil, err
		}
	}
	cfg, err := pgxpool.ParseConfig(os.Getenv("BOOTH_TEST_POSTGRES_DSN"))
	if err != nil {
		return nil, err
	}
	cfg.ConnConfig.RuntimeParams["search_path"] = p.env.Schema
	role := p.env.Role
	cfg.AfterConnect = func(ctx context.Context, c *pgx.Conn) error {
		_, err := c.Exec(ctx, `SET ROLE `+role)
		return err
	}
	cfg.MaxConns = 2
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		return nil, err
	}
	p.pools[k] = pool
	return pool, nil
}

func (p *Pools) StopWrites(apiID, owner, why string) int {
	p.mu.Lock()
	defer p.mu.Unlock()
	p.Stops = append(p.Stops, apiID+"/"+owner+"/"+why)
	n := 0
	for k, pool := range p.pools {
		if strings.HasPrefix(k, apiID+"/") && (owner == "" || strings.HasPrefix(k, apiID+"/"+owner+"/")) {
			pool.Close()
			delete(p.pools, k)
			n++
		}
	}
	return n
}

// StopCount returns how many StopWrites calls were made.
func (p *Pools) StopCount() int {
	p.mu.Lock()
	defer p.mu.Unlock()
	return len(p.Stops)
}

func (p *Pools) closeAll() {
	p.mu.Lock()
	defer p.mu.Unlock()
	for _, pool := range p.pools {
		pool.Close()
	}
}
